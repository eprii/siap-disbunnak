  Future<void> _submit() async {
    FocusScope.of(context).unfocus();
    final bool fieldsValid = _formKey.currentState?.validate() ?? false;
    if (!fieldsValid) {
      _showMessage('Lengkapi seluruh data wajib terlebih dahulu.');
      return;
    }

    if (_tanggalMulai == null || _tanggalAkhir == null || _tanggalSertifikat == null) {
      _showMessage('Semua tanggal wajib dipilih.');
      return;
    }

    if (_pdfFile == null) {
      _showMessage('Dokumen PDF SK wajib dipilih.');
      return;
    }
    final bool confirmed = await _showConfirmDialog();
    if (!confirmed || !mounted) return;
    setState(() { _isSubmitting = true; });
    try {
      final PlatformFile selectedPdf = _pdfFile!;
      final String? localPath = selectedPdf.path;

      if (localPath == null || localPath.trim().isEmpty) {
        throw const SkDocumentException(
          'File PDF tidak dapat dibaca dari perangkat.',
        );
      }

      final _EmployeeHeaderData employee =
          await _employeeFuture;

      await SkDocumentService.instance.createDocument(
        collection: 'sk_diklat',
        storageFolder: 'diklat',
        file: File(localPath),
        originalFileName: selectedPdf.name,
        data: <String, dynamic>{
          'jenis_diklat': _jenisDiklatController.text.trim(),
          'detail_diklat': _detailDiklatController.text.trim(),
          'nama_kegiatan': _namaKegiatanController.text.trim(),
          'lokasi': _lokasiController.text.trim(),
          'penyelenggara': _penyelenggaraController.text.trim(),
          'angkatan': _angkatanController.text.trim(),
          'jumlah_jam': _jumlahJamController.text.trim(),
          'nomor_sertifikat': _nomorSertifikatController.text.trim(),
          'tanggal_mulai': Timestamp.fromDate(_tanggalMulai!),
          'tanggal_akhir': Timestamp.fromDate(_tanggalAkhir!),
          'tanggal_sertifikat': Timestamp.fromDate(_tanggalSertifikat!),
          'nomor_dokumen': _nomorSertifikatController.text.trim(),
          'tanggal_dokumen': Timestamp.fromDate(_tanggalSertifikat!),
          'jenis_sk': 'SK Diklat',
          'nama_pegawai': employee.user?.nama_lengkap.trim() ?? '',
          'nip': employee.user?.nip.trim() ?? '',
          'jabatan_saat_upload':
              employee.profile?.jabatan_sekarang.trim() ?? '',
          'status': 'Pending',
        },
      );

      if (!mounted) return;
      await _showSuccessDialog();
    } on SkDocumentException catch (error) {
      if (!mounted) return;
      _showMessage(error.message);
    } on FirebaseException catch (error) {
      if (!mounted) return;
      _showMessage(
        error.message ?? 'Firestore gagal menyimpan data SK.',
      );
    } catch (error, stackTrace) {
      debugPrint('SAVE SK ERROR: $error');
      debugPrintStack(stackTrace: stackTrace);
      if (!mounted) return;
      _showMessage('Gagal menyimpan data SK: $error');
    } finally {
      if (mounted) setState(() { _isSubmitting = false; });
    }
  }


