  /// Mengambil kode dari opsi berbentuk "kode - nama".
  static String ambilKode(String opsi) {
    final int separatorIndex = opsi.indexOf(' - ');

    if (separatorIndex == -1) {
      return opsi.trim();
    }

    return opsi.substring(0, separatorIndex).trim();
  }

  /// Mengambil nama dari opsi berbentuk "kode - nama".
  static String ambilNama(String opsi) {
    final int separatorIndex = opsi.indexOf(' - ');

    if (separatorIndex == -1) {
      return opsi.trim();
    }

    return opsi.substring(separatorIndex + 3).trim();
  }

  /// Mencari opsi penghargaan berdasarkan kode.
  static String? cariPenghargaanBerdasarkanKode(String kode) {
    final String kodeBersih = kode.trim();

    for (final String opsi in jenisPenghargaanAtauJasa) {
      if (ambilKode(opsi) == kodeBersih) {
        return opsi;
      }
    }

    return null;
  }

  /// Mencari diklat teknis/kursus berdasarkan kode atau kata pada nama.
  static List<String> cariDiklatTeknisAtauKursus(String query) {
    final String kataKunci = query.trim().toLowerCase();

    if (kataKunci.isEmpty) {
      return diklatTeknisAtauKursus;
    }

    return diklatTeknisAtauKursus
        .where((String opsi) {
          return opsi.toLowerCase().contains(kataKunci);
        })
        .toList(growable: false);
  }
